"""Build Chaos Drops into dist/ChaosDrops.mcaddon.

    python3 build.py

Generates both packs into build/, validates every cross-reference, syntax-checks the
scripts with Node (if installed) and zips the result.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "tools"))

import art  # noqa: E402
import content as C  # noqa: E402
import models  # noqa: E402

BUILD = os.path.join(ROOT, "build")
DIST = os.path.join(ROOT, "dist")
BP = os.path.join(BUILD, "ChaosDrops_BP")
RP = os.path.join(BUILD, "ChaosDrops_RP")
errors = []


def write_json(base, rel, data):
    path = os.path.join(base, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def write_text(base, rel, text):
    path = os.path.join(base, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def save_png(base, rel, canvas):
    path = os.path.join(base, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    canvas.save(path)


def generate():
    shutil.rmtree(BUILD, ignore_errors=True)

    # ---- behavior pack
    write_json(BP, "manifest.json", C.bp_manifest())
    save_png(BP, "pack_icon.png", art.pack_icon("behavior"))
    for name, fn in C.ENTITIES.items():
        write_json(BP, f"entities/{name}.json", fn())
    write_json(BP, "spawn_rules/loot_goblin.json", C.goblin_spawn_rules())
    for name, fn in C.ITEMS.items():
        write_json(BP, f"items/{name}.json", fn())
    write_json(BP, "blocks/lucky_block.json", C.lucky_block())
    for name, recipe in C.RECIPES.items():
        write_json(BP, f"recipes/{name}.json", recipe)
    write_json(BP, C.RANDOM_ITEM, C.random_item_table())
    for path, table in {**C.vanilla_overrides(), **C.boss_loot()}.items():
        write_json(BP, path, table)

    scripts_src = os.path.join(ROOT, "src", "scripts")
    os.makedirs(os.path.join(BP, "scripts"), exist_ok=True)
    for f in os.listdir(scripts_src):
        if f.endswith(".js"):
            shutil.copy(os.path.join(scripts_src, f), os.path.join(BP, "scripts", f))
    pool = C.item_pool()
    write_text(BP, "scripts/pool.js",
               "// Generated by build.py from the game's item catalog. Do not edit.\n"
               f"export const POOL = {json.dumps([[i, w] for i, w in pool])};\n"
               f"export const VALUABLES = {json.dumps(C.VALUABLES)};\n")

    # ---- resource pack
    write_json(RP, "manifest.json", C.rp_manifest())
    save_png(RP, "pack_icon.png", art.pack_icon("resource"))
    specs = {}
    for fn in models.MODELS:
        spec = fn()
        geometry, textures, animations = models.build_model(spec)
        specs[spec["name"]] = spec
        write_json(RP, f"models/entity/chaos/{spec['name']}.geo.json", geometry)
        write_json(RP, f"animations/chaos/{spec['name']}.animation.json", animations)
        for tex_name, canvas in textures.items():
            save_png(RP, f"textures/entity/chaos/{tex_name}.png", canvas)
        write_json(RP, f"entity/chaos/{spec['name']}.entity.json", C.client_entity(spec["name"], spec))
    write_json(RP, "render_controllers/chaos.render_controllers.json", C.RENDER_CONTROLLERS)
    for name, canvas in art.item_textures().items():
        save_png(RP, f"textures/items/chaos/{name}.png", canvas)
    save_png(RP, "textures/blocks/chaos/lucky_block.png", art.lucky_block())
    write_json(RP, "textures/item_texture.json", C.item_texture_json())
    write_json(RP, "textures/terrain_texture.json", C.terrain_texture_json())
    write_json(RP, "blocks.json", C.BLOCKS_JSON)
    write_text(RP, "texts/en_US.lang", C.lang_lines())
    write_json(RP, "texts/languages.json", ["en_US"])
    write_text(BP, "texts/en_US.lang", "pack.name=Chaos Drops\npack.description=" + C.DESCRIPTION + "\n")
    write_json(BP, "texts/languages.json", ["en_US"])
    return specs


# --------------------------------------------------------------------------- validation

def check(cond, msg):
    if not cond:
        errors.append(msg)


def load_all_json(base):
    out = {}
    for root, _, files in os.walk(base):
        for f in files:
            if f.endswith(".json"):
                path = os.path.join(root, f)
                try:
                    with open(path, encoding="utf-8") as fh:
                        out[os.path.relpath(path, base)] = json.load(fh)
                except Exception as e:  # noqa: BLE001
                    errors.append(f"bad JSON {path}: {e}")
    return out


def validate(specs):
    bp = load_all_json(BP)
    rp = load_all_json(RP)
    vanilla = {i for i, _ in C.vanilla_items()}
    custom = {f"{C.NS}:{n}" for n in C.ITEMS} | {f"{C.NS}:lucky_block"}
    known_items = vanilla | custom | {"minecraft:book"}
    with open(os.path.join(C.DATA_DIR, "vanilla_loot_tables.json")) as f:
        known_tables = set(json.load(f)) | {p for p in bp if p.startswith("loot_tables/")}

    # loot tables
    for path, table in bp.items():
        if not path.startswith("loot_tables/"):
            continue
        for pool in table.get("pools", []):
            for entry in pool.get("entries", []):
                if entry["type"] == "item":
                    check(entry["name"] in known_items, f"{path}: unknown item {entry['name']}")
                elif entry["type"] == "loot_table":
                    check(entry["name"] in known_tables, f"{path}: missing table {entry['name']}")

    # entity loot references, recipes
    for path, data in bp.items():
        if path.startswith("entities/"):
            loot = data["minecraft:entity"]["components"].get("minecraft:loot", {}).get("table")
            check(loot is None or loot in known_tables, f"{path}: missing loot table {loot}")
        if path.startswith("recipes/"):
            body = next(iter(v for k, v in data.items() if k.startswith("minecraft:recipe")))
            items = [k["item"] for k in body.get("key", {}).values()] + [i["item"] for i in body.get("ingredients", [])]
            items.append(body["result"]["item"])
            for it in items:
                check(it in known_items, f"{path}: unknown item {it}")
            if "pattern" in body:
                used = set("".join(body["pattern"])) - {" "}
                check(used == set(body["key"]), f"{path}: pattern/key mismatch")
        if path.startswith("items/"):
            placer = data["minecraft:item"]["components"].get("minecraft:entity_placer")
            if placer:
                check(f"entities/{placer['entity'].split(':')[1]}.json" in bp, f"{path}: placer entity missing")

    # resource pack references
    geos = {g["description"]["identifier"]: g for d in rp.values() if "minecraft:geometry" in d for g in d["minecraft:geometry"]}
    anims = {k for d in rp.values() if "animations" in d and isinstance(d["animations"], dict) for k in d["animations"]}
    for path, data in rp.items():
        if not path.startswith("entity/"):
            continue
        desc = data["minecraft:client_entity"]["description"]
        for tex in desc["textures"].values():
            check(os.path.exists(os.path.join(RP, tex + ".png")), f"{path}: missing texture {tex}")
        for geo in desc["geometry"].values():
            check(geo in geos, f"{path}: missing geometry {geo}")
        for anim in desc["animations"].values():
            check(anim in anims, f"{path}: missing animation {anim}")
        for a in desc["scripts"]["animate"]:
            name = a if isinstance(a, str) else next(iter(a))
            check(name in desc["animations"], f"{path}: animate refers to unknown {name}")
        check(f"entities/{desc['identifier'].split(':')[1]}.json" in bp, f"{path}: no behavior entity")

    # geometry UVs inside the texture
    for ident, g in geos.items():
        d = g["description"]
        bones = {b["name"] for b in g["bones"]}
        for b in g["bones"]:
            check(b.get("parent") in (None, *bones), f"{ident}: bad parent {b.get('parent')}")
            for c in b.get("cubes", []):
                w, h, dp = c["size"]
                u, v = c["uv"]
                check(u + 2 * (w + dp) <= d["texture_width"] and v + dp + h <= d["texture_height"], f"{ident}: UV out of bounds")

    for key, entry in rp["textures/item_texture.json"]["texture_data"].items():
        check(os.path.exists(os.path.join(RP, entry["textures"] + ".png")), f"item texture missing: {key}")
    for key, entry in rp["textures/terrain_texture.json"]["texture_data"].items():
        check(os.path.exists(os.path.join(RP, entry["textures"] + ".png")), f"terrain texture missing: {key}")
    for path, data in bp.items():
        if path.startswith("items/"):
            icon = data["minecraft:item"]["components"]["minecraft:icon"]["textures"]["default"]
            check(icon in rp["textures/item_texture.json"]["texture_data"], f"{path}: icon {icon} not registered")

    lang = open(os.path.join(RP, "texts/en_US.lang"), encoding="utf-8").read()
    for n in C.ITEMS:
        check(f"item.{C.NS}:{n}.name=" in lang, f"lang missing item {n}")
    for n in C.ENTITIES:
        check(f"entity.{C.NS}:{n}.name=" in lang, f"lang missing entity {n}")

    # manifests
    bpm, rpm = bp["manifest.json"], rp["manifest.json"]
    check(any(d.get("uuid") == rpm["header"]["uuid"] for d in bpm["dependencies"]), "BP does not depend on RP")
    check(any(d.get("uuid") == bpm["header"]["uuid"] for d in rpm["dependencies"]), "RP does not depend on BP")

    validate_scripts()
    return bp, rp


def validate_scripts():
    folder = os.path.join(BP, "scripts")
    exports = {}
    sources = {}
    for f in os.listdir(folder):
        src = open(os.path.join(folder, f), encoding="utf-8").read()
        sources[f] = src
        names = set(re.findall(r"export (?:const|let|function\*?|class) (\w+)", src))
        exports[f] = names
    for f, src in sources.items():
        for names, mod in re.findall(r"import \{([^}]+)\} from \"\./([\w.]+)\"", src):
            check(mod in exports, f"{f}: imports missing module {mod}")
            for n in (x.strip().split(" as ")[0] for x in names.split(",") if x.strip()):
                check(n in exports.get(mod, ()), f"{f}: {mod} does not export {n}")
        for mod in re.findall(r"import \* as \w+ from \"\./([\w.]+)\"", src):
            check(mod in exports, f"{f}: imports missing module {mod}")
    node = shutil.which("node")
    if not node:
        print("  (node not found: skipped JS syntax check)")
        return
    for f in sources:
        r = subprocess.run([node, "--check", os.path.join(folder, f)], capture_output=True, text=True)
        check(r.returncode == 0, f"JS syntax error in {f}: {r.stderr.strip()}")


# --------------------------------------------------------------------------- packaging

def zip_dir(zf, folder, prefix):
    for root, _, files in sorted(os.walk(folder)):
        for f in sorted(files):
            full = os.path.join(root, f)
            arc = os.path.join(prefix, os.path.relpath(full, folder)) if prefix else os.path.relpath(full, folder)
            zi = zipfile.ZipInfo(arc.replace(os.sep, "/"), date_time=(2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            with open(full, "rb") as fh:
                zf.writestr(zi, fh.read())


def package():
    os.makedirs(DIST, exist_ok=True)
    targets = {
        "ChaosDrops.mcaddon": [(BP, "ChaosDrops_BP"), (RP, "ChaosDrops_RP")],
        "ChaosDrops_BP.mcpack": [(BP, "")],
        "ChaosDrops_RP.mcpack": [(RP, "")],
    }
    for name, parts in targets.items():
        path = os.path.join(DIST, name)
        with zipfile.ZipFile(path, "w") as zf:
            for folder, prefix in parts:
                zip_dir(zf, folder, prefix)
        print(f"  {os.path.relpath(path, ROOT)}  ({os.path.getsize(path) // 1024} KB)")


def main():
    print("Generating packs...")
    specs = generate()
    print("Validating...")
    bp, rp = validate(specs)
    if errors:
        print(f"\n{len(errors)} problem(s):")
        for e in errors:
            print("  -", e)
        sys.exit(1)
    n_loot = sum(1 for p in bp if p.startswith("loot_tables/"))
    print(f"  OK: {len(bp)} behavior files ({n_loot} loot tables), {len(rp)} resource JSON files, "
          f"{len(C.item_pool())} items in the random pool")
    print("Packaging...")
    package()


if __name__ == "__main__":
    main()
